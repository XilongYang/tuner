// IndexedDB access: opening the database, and the one helper every write goes
// through.
//
// `transact()` exists because the previous design had no such helper, so each
// multi-store write was hand-rolled and none of them were atomic. Deleting a
// record and recording its tombstone were two separate transactions: if the
// second failed, the record was gone locally and the next sync -- seeing a
// deletion it had never been told about -- downloaded it straight back.
// "Clear everything" was worse, at N+3 transactions. Here a caller names the
// stores it needs and gets one transaction across all of them.

export const DB_NAME = 'tuner';
export const DB_VERSION = 2;

export const SESSIONS = 'sessions';
export const FOLDERS = 'folders';
export const VOCAB = 'vocab';
export const TOMBSTONES = 'tombstones';
export const CONTENT = 'content';
export const ALL_STORES = [SESSIONS, FOLDERS, VOCAB, TOMBSTONES, CONTENT];

/** True when this browser can store anything at all; every caller checks once. */
export function isSupported() {
  return typeof indexedDB !== 'undefined' && indexedDB !== null;
}

let dbPromise = null;
/** Which open this is, so a connection only ever forgets its own. */
let generation = 0;

export function openDb() {
  if (dbPromise) return dbPromise;
  const mine = ++generation;
  // Set once this open has given up. A blocked open reports failure straight
  // away, but the request behind it can still succeed later -- when the tab in
  // the way closes -- and that connection must be closed rather than left open
  // with nothing referencing it.
  let abandoned = false;

  dbPromise = new Promise((resolve, reject) => {
    const request = indexedDB.open(DB_NAME, DB_VERSION);
    request.onupgradeneeded = () => {
      const db = request.result;
      // Sessions, folders and vocab entries are all keyed by their own `id`
      // (folders included -- ids are generated by the caller, never by
      // autoIncrement, so a record's identity does not depend on which device
      // created it). Tombstones are keyed by "kind:targetId".
      if (!db.objectStoreNames.contains(SESSIONS)) db.createObjectStore(SESSIONS, { keyPath: 'id' });
      if (!db.objectStoreNames.contains(FOLDERS)) db.createObjectStore(FOLDERS, { keyPath: 'id' });
      if (!db.objectStoreNames.contains(VOCAB)) db.createObjectStore(VOCAB, { keyPath: 'id' });
      if (!db.objectStoreNames.contains(TOMBSTONES)) db.createObjectStore(TOMBSTONES, { keyPath: 'id' });
      // Content lives apart from the records that reference it, keyed by the
      // same blob path the container uses, so a record can be rewritten as
      // often as an edit demands without its audio being rewritten with it.
      // See ./content.js for why that is not an optimisation.
      if (!db.objectStoreNames.contains(CONTENT)) db.createObjectStore(CONTENT, { keyPath: 'path' });
    };
    request.onsuccess = () => {
      const db = request.result;
      if (abandoned) {
        db.close();
        return;
      }
      // Another tab wants to upgrade the schema, and it cannot while this
      // connection is open. Holding on would hang that tab for as long as this
      // one lives, so this one lets go -- and forgets the connection, so the
      // next call opens a fresh one at whatever version now exists.
      db.onversionchange = () => {
        db.close();
        if (generation === mine) dbPromise = null;
      };
      resolve(db);
    };
    request.onerror = () => {
      abandoned = true;
      reject(dbError(request.error, `Opening the ${DB_NAME} database`));
    };
    // The mirror image: this tab needs an upgrade and an older one is in the
    // way. Without this the open never settles at all -- no success, no error
    // -- and the app waits forever with nothing on screen to say why.
    request.onblocked = () => {
      abandoned = true;
      reject(new Error(
        `Opening the ${DB_NAME} database is blocked: another tab is still using an older version of this app. Close it and reload.`,
      ));
    };
  }).catch((err) => {
    // A failed open is not cached. Otherwise one blocked or refused attempt is
    // handed to every later call for the life of the page: the tab in the way
    // closes, the user reloads nothing, and storage stays dead with no way
    // back except a reload they were never told to do.
    if (generation === mine) dbPromise = null;
    throw err;
  });
  return dbPromise;
}

/** Only for tests: drops the cached connection so a fresh one is opened. */
export function resetDbForTests() {
  dbPromise = null;
}

/**
 * Every failure out of this module, as something a caller can actually catch.
 *
 * IndexedDB reports failures with no error object at all: WebKit aborts a
 * transaction with `tx.error === null`, and a request that failed inside one
 * can carry null too. Rejecting with that null is how a failed save becomes a
 * silent one -- the handler reads `.message` of null, throws inside its own
 * catch block, and the write that did not happen is reported to nobody.
 *
 * @param {unknown} err  whatever IndexedDB offered, including nothing
 * @param {string} what  the operation, for the message it may have to invent
 */
export function dbError(err, what) {
  if (err && (err.name || err.message)) return err;
  const failure = new Error(`${what} failed, and the browser gave no reason`);
  failure.name = 'UnknownError';
  return failure;
}

/** One IndexedDB request as a promise. */
export function request(req, what = 'A database request') {
  return new Promise((resolve, reject) => {
    req.onsuccess = () => resolve(req.result);
    req.onerror = () => reject(dbError(req.error, what));
  });
}

/**
 * Run `fn` inside one transaction over `storeNames` and resolve once it has
 * actually committed.
 *
 * `fn` receives a lookup of the stores it asked for and may await requests made
 * on them; it must not await anything else, because an IndexedDB transaction
 * closes as soon as its microtask queue drains. Hashing, encoding and any
 * network work therefore happen before the call, not inside it -- which is also
 * why the result of `fn` is passed through: the caller assembles the records
 * first, then commits them in one atomic step.
 *
 * Resolution waits for `oncomplete`, not for `fn` returning, so a caller that
 * awaits this knows the data is durable. Abort and error both reject.
 *
 * @template T
 * @param {string[]} storeNames
 * @param {'readonly'|'readwrite'} mode
 * @param {(stores: Record<string, IDBObjectStore>) => T | Promise<T>} fn
 * @returns {Promise<T>}
 */
export async function transact(storeNames, mode, fn) {
  const db = await openDb();
  const tx = db.transaction(storeNames, mode);
  const stores = {};
  for (const name of storeNames) stores[name] = tx.objectStore(name);

  const committed = new Promise((resolve, reject) => {
    tx.oncomplete = () => resolve();
    tx.onerror = () => reject(dbError(tx.error, `The ${mode} transaction over ${storeNames.join(', ')}`));
    tx.onabort = () => reject(dbError(tx.error, `The ${mode} transaction over ${storeNames.join(', ')} was aborted and`));
  });

  let result;
  try {
    result = await fn(stores);
  } catch (err) {
    // The abort below makes `committed` reject too, and nothing awaits it on
    // this path -- without claiming that rejection it surfaces later as an
    // unhandled rejection that outlives the caller (and, in a test runner,
    // fails whichever test happens to be running at the time). `err` is the
    // real failure; the abort is a consequence of it.
    committed.catch(() => {});
    try { tx.abort(); } catch { /* already finished */ }
    throw err;
  }
  await committed;
  return result;
}
