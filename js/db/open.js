// IndexedDB access: opening the database, and the one helper every write goes
// through.
//
// `transact()` exists because the previous design had no such helper, so each
// multi-store write was hand-rolled and none of them were atomic. Deleting a
// record and recording its tombstone were two separate transactions: if the
// second failed, the record was gone locally and the next sync -- seeing a
// deletion it had never been told about -- downloaded it straight back.
// "Clear everything" was worse, at N+3 transactions. Here a caller names the
// stores it needs and gets one transaction across all of them.

export const DB_NAME = 'tuner';
export const DB_VERSION = 1;

export const SESSIONS = 'sessions';
export const FOLDERS = 'folders';
export const VOCAB = 'vocab';
export const TOMBSTONES = 'tombstones';
export const ALL_STORES = [SESSIONS, FOLDERS, VOCAB, TOMBSTONES];

/** True when this browser can store anything at all; every caller checks once. */
export function isSupported() {
  return typeof indexedDB !== 'undefined' && indexedDB !== null;
}

let dbPromise = null;

export function openDb() {
  if (dbPromise) return dbPromise;
  dbPromise = new Promise((resolve, reject) => {
    const request = indexedDB.open(DB_NAME, DB_VERSION);
    request.onupgradeneeded = () => {
      const db = request.result;
      // Sessions, folders and vocab entries are all keyed by their own `id`
      // (folders included -- ids are generated by the caller, never by
      // autoIncrement, so a record's identity does not depend on which device
      // created it). Tombstones are keyed by "kind:targetId".
      if (!db.objectStoreNames.contains(SESSIONS)) db.createObjectStore(SESSIONS, { keyPath: 'id' });
      if (!db.objectStoreNames.contains(FOLDERS)) db.createObjectStore(FOLDERS, { keyPath: 'id' });
      if (!db.objectStoreNames.contains(VOCAB)) db.createObjectStore(VOCAB, { keyPath: 'id' });
      if (!db.objectStoreNames.contains(TOMBSTONES)) db.createObjectStore(TOMBSTONES, { keyPath: 'id' });
    };
    request.onsuccess = () => resolve(request.result);
    request.onerror = () => reject(request.error);
  });
  return dbPromise;
}

/** Only for tests: drops the cached connection so a fresh one is opened. */
export function resetDbForTests() {
  dbPromise = null;
}

/** One IndexedDB request as a promise. */
export function request(req) {
  return new Promise((resolve, reject) => {
    req.onsuccess = () => resolve(req.result);
    req.onerror = () => reject(req.error);
  });
}

/**
 * Run `fn` inside one transaction over `storeNames` and resolve once it has
 * actually committed.
 *
 * `fn` receives a lookup of the stores it asked for and may await requests made
 * on them; it must not await anything else, because an IndexedDB transaction
 * closes as soon as its microtask queue drains. Hashing, encoding and any
 * network work therefore happen before the call, not inside it -- which is also
 * why the result of `fn` is passed through: the caller assembles the records
 * first, then commits them in one atomic step.
 *
 * Resolution waits for `oncomplete`, not for `fn` returning, so a caller that
 * awaits this knows the data is durable. Abort and error both reject.
 *
 * @template T
 * @param {string[]} storeNames
 * @param {'readonly'|'readwrite'} mode
 * @param {(stores: Record<string, IDBObjectStore>) => T | Promise<T>} fn
 * @returns {Promise<T>}
 */
export async function transact(storeNames, mode, fn) {
  const db = await openDb();
  const tx = db.transaction(storeNames, mode);
  const stores = {};
  for (const name of storeNames) stores[name] = tx.objectStore(name);

  const committed = new Promise((resolve, reject) => {
    tx.oncomplete = () => resolve();
    tx.onerror = () => reject(tx.error);
    tx.onabort = () => reject(tx.error || new Error('Transaction aborted'));
  });

  let result;
  try {
    result = await fn(stores);
  } catch (err) {
    // The abort below makes `committed` reject too, and nothing awaits it on
    // this path -- without claiming that rejection it surfaces later as an
    // unhandled rejection that outlives the caller (and, in a test runner,
    // fails whichever test happens to be running at the time). `err` is the
    // real failure; the abort is a consequence of it.
    committed.catch(() => {});
    try { tx.abort(); } catch { /* already finished */ }
    throw err;
  }
  await committed;
  return result;
}
